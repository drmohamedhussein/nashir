/**
 * @return array<string, string>
 */
function nashir_i18n(): array {
	static $cache = null;
	if ( is_array( $cache ) ) {
		return $cache;
	}

	$en    = 'en' === nashir_locale();
	$cache = $en ? nashir_en() : nashir_ar();
	return $cache;
}

function nashir_t( string $key ): string {
	$all = nashir_i18n();
	if ( isset( $all[ $key ] ) ) {
		return $all[ $key ];
	}
	$en = nashir_en();
	return $en[ $key ] ?? $key;
}

